@app.command()
def governance() -> None:
    """Validate current governance configuration and warn about gaps."""
    from enterprise_claude.governance import GovernanceConfig, GovernanceLayer

    api_key = os.environ.get("ANTHROPIC_API_KEY", "")

    # Build config from environment variables
    pii_filter = _bool_env("ECL_PII_FILTER", "true")
    gxp_mode = _bool_env("ECL_GXP_MODE", "false")
    max_prompt = int(os.environ.get("ECL_MAX_PROMPT_LENGTH", "100000"))
    require_sys = _bool_env("ECL_REQUIRE_SYSTEM_PROMPT", "true")
    constitutional = _bool_env("ECL_CONSTITUTIONAL_AI", "true")
    blocked_raw = os.environ.get("ECL_BLOCKED_KEYWORDS", "")
    blocked_kw: list[str] = [k.strip() for k in blocked_raw.split(",") if k.strip()]

    cfg = GovernanceConfig(
        pii_filter=pii_filter,
        gxp_mode=gxp_mode,
        max_prompt_length=max_prompt,
        require_system_prompt=require_sys,
        constitutional_ai=constitutional,
        blocked_keywords=blocked_kw,
    )
    # Instantiate the layer to confirm it initialises cleanly
    _layer = GovernanceLayer(config=cfg)

    def _row(label: str, enabled: bool, warn_if_off: bool = True) -> str:
        if enabled:
            return f"[bold green]✅[/bold green]  {label}"
        elif warn_if_off:
            return f"[bold yellow]⚠[/bold yellow]   {label} [dim](disabled)[/dim]"
        else:
            return f"[dim]—   {label} (disabled)[/dim]"

    kw_note: str
    if not blocked_kw:
        kw_note = " [yellow](none — consider adding topic-specific terms)[/yellow]"
    elif len(blocked_kw) <= 3:
        kw_note = f" ({', '.join(blocked_kw)})"
    else:
        kw_note = f" ({', '.join(blocked_kw[:3])}, …+{len(blocked_kw) - 3} more)"

    settings_lines = [
        "[bold]Feature flags:[/bold]\n",
        _row("PII Filter", cfg.pii_filter),
        _row("GxP / Regulatory Mode", cfg.gxp_mode, warn_if_off=False),
        _row("Require System Prompt", cfg.require_system_prompt),
        _row("Constitutional AI", cfg.constitutional_ai),
        _row("Log Violations", cfg.log_violations),
        "",
        f"[bold]Max Prompt Length:[/bold]  {cfg.max_prompt_length:,} chars",
        f"[bold]Blocked Keywords:[/bold]   {len(blocked_kw)} configured{kw_note}",
    ]

    # Collect warnings
    warnings: list[str] = []
    if not api_key:
        warnings.append("[bold red]⚠  ANTHROPIC_API_KEY is not set[/bold red]")
    if not cfg.pii_filter:
        warnings.append(
            "[yellow]⚠  PII filter disabled — sensitive data may appear in logs[/yellow]"
        )
    if not cfg.require_system_prompt:
        warnings.append(
            "[yellow]⚠  System prompt not required — agents may behave unpredictably[/yellow]"
        )
    if not blocked_kw:
        warnings.append("[yellow]⚠  No blocked keywords configured[/yellow]")

    if warnings:
        settings_lines.append("\n[bold]Warnings:[/bold]")
        settings_lines.extend(warnings)
        border = "yellow"
    else:
        settings_lines.append("\n[bold green]✅ Configuration looks healthy![/bold green]")
        border = "green"

    console.print(
        Panel(
            "\n".join(settings_lines),
            title="[bold cyan]Governance Configuration[/bold cyan]",
            border_style=border,
            padding=(1, 2),
        )
    )


