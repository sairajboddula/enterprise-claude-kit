@agents_app.command("list")
def agents_list() -> None:
    """List all agents seen in the audit log with call and cost stats."""

    async def _run() -> tuple[list[dict[str, Any]], dict[str, float]]:
        import aiosqlite

        agents_data: list[dict[str, Any]] = []
        if Path(_DEFAULT_AUDIT_DB).exists():
            async with aiosqlite.connect(_DEFAULT_AUDIT_DB) as db:
                db.row_factory = aiosqlite.Row
                async with db.execute(
                    """
                    SELECT
                        agent_id,
                        persona,
                        model_used          AS model,
                        COUNT(*)            AS total_calls,
                        MAX(timestamp)      AS last_active
                    FROM audit_events
                    GROUP BY agent_id, persona, model_used
                    ORDER BY last_active DESC
                    """
                ) as cur:
                    async for row in cur:
                        agents_data.append(dict(row))

        cost_by_agent: dict[str, float] = {}
        if Path(_DEFAULT_MONITOR_DB).exists():
            async with aiosqlite.connect(_DEFAULT_MONITOR_DB) as db:
                db.row_factory = aiosqlite.Row
                async with db.execute(
                    "SELECT agent_id, SUM(cost_usd) AS total "
                    "FROM usage_records GROUP BY agent_id"
                ) as cur:
                    async for row in cur:
                        cost_by_agent[row["agent_id"]] = round(row["total"] or 0.0, 6)

        return agents_data, cost_by_agent

    try:
        agents_data, cost_by_agent = asyncio.run(_run())
    except Exception:  # noqa: BLE001
        console.print_exception()
        raise typer.Exit(code=1)

    if not agents_data:
        console.print(
            Panel(
                "[cyan]No agents have been deployed yet.[/cyan]\n\n"
                "Run [bold]ecl agents deploy <name>[/bold] to create your first agent.",
                title="Agents",
                border_style="blue",
                padding=(1, 2),
            )
        )
        return

    table = Table(
        title="Deployed Agents",
        box=box.ROUNDED,
        show_header=True,
        header_style="bold cyan",
    )
    table.add_column("Agent ID", style="dim", max_width=16)
    table.add_column("Persona")
    table.add_column("Model")
    table.add_column("Status")
    table.add_column("Calls", justify="right")
    table.add_column("Cost USD", justify="right")
    table.add_column("Last Active")

    for agent in agents_data:
        agent_id: str = agent["agent_id"]
        short_id = (agent_id[:12] + "…") if len(agent_id) > 13 else agent_id
        cost = cost_by_agent.get(agent_id, 0.0)

        last_ts: str = agent.get("last_active") or ""
        try:
            last_dt = datetime.fromisoformat(last_ts)
            last_str = last_dt.strftime("%Y-%m-%d %H:%M")
        except (ValueError, AttributeError):
            last_str = last_ts or "—"

        status_text = Text("● active", style="green")

        table.add_row(
            short_id,
            agent["persona"],
            agent["model"],
            status_text,
            str(agent["total_calls"]),
            f"${cost:.4f}",
            last_str,
        )

    console.print(table)


