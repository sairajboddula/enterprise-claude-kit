@app.command()
def cost(
    days: Annotated[
        int,
        typer.Option("--days", "-d", help="Look-back window in days"),
    ] = 7,
) -> None:
    """Show spend breakdown by model and persona."""

    async def _run() -> tuple[Any, Any, dict[str, int], dict[str, int]]:
        import aiosqlite

        from enterprise_claude.token_monitor import MonitorConfig, TokenMonitor

        monitor = TokenMonitor(
            config=MonitorConfig(
                daily_budget_usd=_DEFAULT_BUDGET_USD,
                db_path=_DEFAULT_MONITOR_DB,
            )
        )
        await monitor.initialize()

        now = datetime.now(tz=UTC)
        start_dt = now - timedelta(days=days)
        summary = await monitor.get_cost_summary(start_date=start_dt, end_date=now)
        budget_status = await monitor.check_budget()

        # Per-model and per-persona call counts from audit DB
        model_calls: dict[str, int] = {}
        persona_calls: dict[str, int] = {}
        if Path(_DEFAULT_AUDIT_DB).exists():
            start_iso = start_dt.isoformat()
            async with aiosqlite.connect(_DEFAULT_AUDIT_DB) as db:
                db.row_factory = aiosqlite.Row
                async with db.execute(
                    "SELECT model_used, COUNT(*) AS cnt FROM audit_events "
                    "WHERE timestamp >= ? GROUP BY model_used",
                    (start_iso,),
                ) as cur:
                    async for row in cur:
                        model_calls[row["model_used"]] = row["cnt"]
                async with db.execute(
                    "SELECT persona, COUNT(*) AS cnt FROM audit_events "
                    "WHERE timestamp >= ? GROUP BY persona",
                    (start_iso,),
                ) as cur:
                    async for row in cur:
                        persona_calls[row["persona"]] = row["cnt"]

        return summary, budget_status, model_calls, persona_calls

    try:
        summary, budget_status, model_calls, persona_calls = asyncio.run(_run())
    except Exception:  # noqa: BLE001
        console.print_exception()
        raise typer.Exit(code=1)

    # ── 1. Budget status ──────────────────────────────────────────────────────
    pct = budget_status.pct_used
    bar_width = 38
    filled = int(bar_width * min(pct / 100.0, 1.0))
    empty = bar_width - filled
    if pct < 60:
        bar_color = "green"
    elif pct < 85:
        bar_color = "yellow"
    else:
        bar_color = "red"

    bar = f"[{bar_color}]{'█' * filled}[/{bar_color}]{'░' * empty}"
    budget_lines = [
        f"Daily Budget  {bar}  [{bar_color}]{pct:.1f}%[/{bar_color}]",
        (
            f"[bold]Used:[/bold] ${budget_status.used_usd:.4f}  "
            f"[bold]Budget:[/bold] ${budget_status.budget_usd:.2f}  "
            f"[bold]Remaining:[/bold] ${budget_status.remaining_usd:.4f}"
        ),
    ]
    if budget_status.alert:
        budget_lines.append("\n[bold red]⚠  Budget alert threshold exceeded![/bold red]")

    console.print(
        Panel(
            "\n".join(budget_lines),
            title="[bold cyan]Budget Status (Today)[/bold cyan]",
            border_style=bar_color,
            padding=(1, 2),
        )
    )

    # ── 2. By model ───────────────────────────────────────────────────────────
    model_table = Table(
        title=f"Cost by Model — Last {days} Days",
        box=box.ROUNDED,
        show_header=True,
        header_style="bold cyan",
    )
    model_table.add_column("Model")
    model_table.add_column("Calls", justify="right")
    model_table.add_column("Cost USD", justify="right")

    for model_id, cost_val in sorted(summary.by_model.items(), key=lambda x: -x[1]):
        model_table.add_row(
            model_id,
            str(model_calls.get(model_id, "—")),
            f"${cost_val:.4f}",
        )
    if not summary.by_model:
        model_table.add_row("[dim]No data[/dim]", "—", "—")
    console.print(model_table)

    # ── 3. By persona ─────────────────────────────────────────────────────────
    persona_table = Table(
        title=f"Cost by Persona — Last {days} Days",
        box=box.ROUNDED,
        show_header=True,
        header_style="bold cyan",
    )
    persona_table.add_column("Persona")
    persona_table.add_column("Calls", justify="right")
    persona_table.add_column("Cost USD", justify="right")

    for persona_id, cost_val in sorted(summary.by_persona.items(), key=lambda x: -x[1]):
        persona_table.add_row(
            persona_id,
            str(persona_calls.get(persona_id, "—")),
            f"${cost_val:.4f}",
        )
    if not summary.by_persona:
        persona_table.add_row("[dim]No data[/dim]", "—", "—")
    console.print(persona_table)

    # ── 4. Total summary ──────────────────────────────────────────────────────
    console.print(
        Panel(
            f"[bold]Total Cost:[/bold]    [bold green]${summary.total_usd:.4f}[/bold green] USD\n"
            f"[bold]Total Records:[/bold] {summary.record_count}\n"
            f"[bold]Period:[/bold]        "
            f"{summary.period_start.strftime('%Y-%m-%d')} → {summary.period_end.strftime('%Y-%m-%d')}",
            title=f"[bold cyan]Cost Summary — Last {days} Days[/bold cyan]",
            border_style="cyan",
            padding=(1, 2),
        )
    )


