def _require_api_key() -> str:
    """Return ``ANTHROPIC_API_KEY`` or exit with a helpful error."""
    key = os.environ.get("ANTHROPIC_API_KEY", "")
    if not key:
        err_console.print(
            "[bold red]ANTHROPIC_API_KEY is not set.[/bold red]\n"
            "Run [bold]ecl init[/bold], fill in your .env file, then retry."
        )
        raise typer.Exit(code=1)
    return key


def _bool_env(name: str, default: str = "true") -> bool:
    """Read an env var as a boolean (true/1/yes)."""
    return os.environ.get(name, default).lower().strip() in ("1", "true", "yes")


