@app.command()
def connectors() -> None:
    """List available MCP connectors and their configuration status."""
    registry: list[dict[str, Any]] = []

    # Try the real MCPConnectorRegistry first
    try:
        from enterprise_claude.mcp_connectors import list_connectors

        raw = list_connectors()
        for c in raw:
            registry.append(
                {
                    "name": getattr(c, "name", str(c)),
                    "description": getattr(c, "description", ""),
                    "auth_type": getattr(c, "auth_type", "—"),
                    "required_env": list(getattr(c, "required_env", [])),
                    "tags": list(getattr(c, "tags", [])),
                }
            )
    except Exception:  # noqa: BLE001
        registry = _CONNECTOR_REGISTRY

    table = Table(
        title="MCP Connector Registry",
        box=box.ROUNDED,
        show_header=True,
        header_style="bold cyan",
    )
    table.add_column("Connector", style="bold")
    table.add_column("Description", max_width=38)
    table.add_column("Auth Type")
    table.add_column("Required Env Vars", max_width=36)
    table.add_column("Status", justify="center")

    for c in registry:
        required_env: list[str] = c.get("required_env", [])
        all_set = all(bool(os.environ.get(v)) for v in required_env)
        status_text = Text("✅", style="green") if all_set else Text("❌", style="red")

        # Colour individual env-var names by whether they are set
        env_cell = Text()
        for i, var in enumerate(required_env):
            colour = "green" if os.environ.get(var) else "red"
            env_cell.append(var, style=colour)
            if i < len(required_env) - 1:
                env_cell.append("\n")

        tags = c.get("tags", [])
        name_with_tags = Text(c.get("name", ""))
        if tags:
            name_with_tags.append(f"\n{' '.join('#' + t for t in tags)}", style="dim")

        table.add_row(
            name_with_tags,
            c.get("description", ""),
            c.get("auth_type", "—"),
            env_cell,
            status_text,
        )

    console.print(table)

    configured = sum(
        1
        for c in registry
        if all(bool(os.environ.get(v)) for v in c.get("required_env", []))
    )
    total = len(registry)
    suffix = (
        "  Run [bold]ecl init[/bold] to scaffold a .env.example with all required vars."
        if configured < total
        else ""
    )
    console.print(f"\n[dim]{configured}/{total} connectors fully configured.[/dim]{suffix}")


