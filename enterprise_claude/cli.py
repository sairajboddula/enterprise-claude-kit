@agents_app.command("deploy")
def agents_deploy(
    name: str,
    config: Annotated[
        Path | None,
        typer.Option("--config", "-c", help="Path to agent YAML config file"),
    ] = None,
    persona: Annotated[str, typer.Option("--persona", help="Agent persona label")] = "default",
    system_prompt: Annotated[
        str,
        typer.Option("--system-prompt", help="System prompt for the agent"),
    ] = "You are a helpful AI assistant.",
    model_tier: Annotated[
        str,
        typer.Option("--tier", help="Model tier: default | batch | gated"),
    ] = "default",
) -> None:
    """Deploy a new governed agent (from CLI flags or a YAML config file)."""
    api_key = _require_api_key()

    # Merge config file values when provided
    if config is not None:
        if not config.exists():
            err_console.print(f"Config file not found: {config}")
            raise typer.Exit(code=1)
        try:
            import yaml

            raw: dict[str, Any] = yaml.safe_load(config.read_text(encoding="utf-8")) or {}
            name = raw.get("name", name)
            persona = raw.get("persona", persona)
            system_prompt = raw.get("system_prompt", system_prompt)
            model_tier = raw.get("model_tier", model_tier)
        except ImportError:
            console.print(
                "[yellow]PyYAML not installed; config file options are ignored.[/yellow]"
            )
        except Exception as exc:
            err_console.print(f"Failed to parse config file: {exc}")
            raise typer.Exit(code=1) from exc

    async def _run() -> tuple[str, str]:
        from enterprise_claude.audit import AuditLogger
        from enterprise_claude.orchestrator import AgentOrchestrator
        from enterprise_claude.token_monitor import MonitorConfig, TokenMonitor

        monitor = TokenMonitor(
            config=MonitorConfig(
                daily_budget_usd=_DEFAULT_BUDGET_USD,
                db_path=_DEFAULT_MONITOR_DB,
            )
        )
        audit_log = AuditLogger(db_path=_DEFAULT_AUDIT_DB)
        orch = AgentOrchestrator(
            api_key=api_key,
            monitor=monitor,
            audit_logger=audit_log,
        )
        await orch.initialize()
        agent = await orch.create_agent(
            name=name,
            system_prompt=system_prompt,
            persona=persona,
            model_tier=model_tier,  # type: ignore[arg-type]
        )
        return agent.agent_id, agent.model

    agent_id: str
    resolved_model: str
    with Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        transient=True,
        console=console,
    ) as progress:
        progress.add_task(description=f"Deploying agent [bold]{name}[/bold]…", total=None)
        try:
            agent_id, resolved_model = asyncio.run(_run())
        except Exception:  # noqa: BLE001
            console.print_exception()
            raise typer.Exit(code=1)

    console.print(
        Panel(
            f"[bold green]✅ Agent deployed successfully![/bold green]\n\n"
            f"[bold]Name:[/bold]     {name}\n"
            f"[bold]Agent ID:[/bold] {agent_id}\n"
            f"[bold]Model:[/bold]    {resolved_model}\n"
            f"[bold]Persona:[/bold]  {persona}\n"
            f"[bold]Tier:[/bold]     {model_tier}",
            title="[bold cyan]Agent Deployed[/bold cyan]",
            border_style="green",
            padding=(1, 2),
        )
    )


