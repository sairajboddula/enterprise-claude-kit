@app.command()
def audit(
    start: Annotated[
        str | None,
        typer.Option("--start", help="Start date in YYYY-MM-DD format"),
    ] = None,
    end: Annotated[
        str | None,
        typer.Option("--end", help="End date in YYYY-MM-DD format"),
    ] = None,
    output: Annotated[
        Path,
        typer.Option("--output", "-o", help="Output CSV file path"),
    ] = Path("./audit_export.csv"),
) -> None:
    """Export audit log to CSV for compliance reporting."""
    now = datetime.now(tz=UTC)

    try:
        start_dt = (
            datetime.strptime(start, "%Y-%m-%d").replace(tzinfo=UTC)
            if start
            else now - timedelta(days=30)
        )
        end_dt = (
            datetime.strptime(end, "%Y-%m-%d").replace(tzinfo=UTC)
            if end
            else now
        )
    except ValueError as exc:
        err_console.print(f"Invalid date: {exc}  — use YYYY-MM-DD.")
        raise typer.Exit(code=1) from exc

    if start_dt > end_dt:
        err_console.print("--start must be before --end.")
        raise typer.Exit(code=1)

    async def _run() -> int:
        import csv as _csv

        from enterprise_claude.audit import AuditLogger

        audit_log = AuditLogger(db_path=_DEFAULT_AUDIT_DB)
        await audit_log.initialize()
        await audit_log.export_csv(
            start_date=start_dt,
            end_date=end_dt,
            output_path=str(output),
        )
        out = Path(str(output))
        if out.exists():
            with open(out, encoding="utf-8", newline="") as fh:  # noqa: ASYNC230
                return max(0, sum(1 for _ in _csv.reader(fh)) - 1)  # subtract header row
        return 0

    row_count = 0
    with Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        transient=True,
        console=console,
    ) as progress:
        progress.add_task(description="Exporting audit log…", total=None)
        try:
            row_count = asyncio.run(_run())
        except Exception:  # noqa: BLE001
            console.print_exception()
            raise typer.Exit(code=1)

    console.print(
        Panel(
            f"[bold green]✅ Audit export complete![/bold green]\n\n"
            f"[bold]Rows exported:[/bold] {row_count}\n"
            f"[bold]Period:[/bold]       {start_dt.date()} → {end_dt.date()}\n"
            f"[bold]Output:[/bold]       {output.resolve()}",
            title="[bold cyan]Audit Export[/bold cyan]",
            border_style="cyan",
            padding=(1, 2),
        )
    )


