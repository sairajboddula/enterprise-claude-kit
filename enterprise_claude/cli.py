@app.command()
def init(
    directory: Annotated[
        Path,
        typer.Option("--dir", "-d", help="Target directory (default: current directory)"),
    ] = Path("."),
) -> None:
    """Scaffold .env.example and ecl_config.yaml in the target directory."""
    directory = directory.resolve()
    directory.mkdir(parents=True, exist_ok=True)

    env_path = directory / ".env.example"
    config_path = directory / "ecl_config.yaml"

    created: list[str] = []
    skipped: list[str] = []

    for path, content in [(env_path, _ENV_EXAMPLE), (config_path, _ECL_CONFIG_YAML)]:
        if not path.exists():
            path.write_text(content, encoding="utf-8")
            created.append(str(path))
        else:
            skipped.append(str(path))

    if skipped:
        for s in skipped:
            console.print(f"[yellow]⚠  Skipped (already exists):[/yellow] {s}")

    next_steps = (
        "1. [bold]cp .env.example .env[/bold]\n"
        "2. Set [cyan]ANTHROPIC_API_KEY[/cyan] and any connector credentials\n"
        "3. Review [cyan]ecl_config.yaml[/cyan] — adjust budget, governance, and wave schedule\n"
        "4. Run [bold]ecl governance check[/bold] to validate your configuration"
    )

    lines: list[str] = ["[bold green]✅ Enterprise Claude Kit initialized![/bold green]\n"]
    if created:
        lines.append("[bold]Files created:[/bold]")
        for f in created:
            lines.append(f"  • {f}")
        lines.append("")
    lines.append("[bold]Next steps:[/bold]")
    lines.append(next_steps)

    console.print(
        Panel(
            "\n".join(lines),
            title="[bold cyan]enterprise-claude-kit[/bold cyan]",
            border_style="cyan",
            padding=(1, 2),
        )
    )


